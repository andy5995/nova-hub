@asynccontextmanager
async def lifespan(app: FastAPI):
    """Startup and shutdown events"""
    # Initialize logging FIRST before any other operations
    init_logging_from_config(config._raw)
    logger = get_logger(context="startup")

    # Validate JWT secret strength before doing anything else
    from backend.core.security import validate_jwt_secret
    try:
        validate_jwt_secret(config.security.jwt_secret)
    except ValueError as e:
        logger.error(f"STARTUP ABORTED: {e}")
        sys.exit(1)

    # Initialize database
    db_path = config.database.path
    database_url = f"sqlite:///{db_path}"
    database = init_database(database_url)
    app.state.database = database
    app.state.config = config

    # Note: Run migrations manually with: alembic upgrade head
    # Automatic migrations disabled to prevent startup hangs

    # A game reset can't survive a restart: settle any left half-done, putting
    # the game back if the hub stopped with its editor open.
    from backend.services.game_reset.perform import recover
    recovery_db = get_session()
    try:
        recover(recovery_db, config._raw)
    except Exception as e:
        logger.exception(f"Could not settle interrupted game resets: {e}")
    finally:
        recovery_db.close()

    import asyncio

    # Honour [processing] retention_days. Runs once at startup and daily after,
    # so a hub that is restarted often still prunes exactly once per day's worth
    # of uptime rather than on every boot. See retention_service.py for why this
    # blanks bulk columns instead of deleting rows.
    app.state.retention_task = asyncio.create_task(_retention_loop(config))

    # Processing starts on an upload, so packets left unprocessed when the hub
    # stopped would otherwise wait for the next one.
    from backend.models.database import Packet
    from backend.services.processing_service import trigger_processing
    pending_db = get_session()
    try:
        if pending_db.query(Packet.id).filter(Packet.processed_at == None).first():
            trigger_processing()
    finally:
        pending_db.close()

    logger.info("Nova Hub started successfully")

    yield

    # Shutdown
    task = getattr(app.state, "retention_task", None)
    if task is not None:
        task.cancel()

    logger.info("Nova Hub shutting down...")


async def _retention_loop(config):
    """Daily retention pass.

    Deliberately a plain loop rather than a scheduler dependency: it has one
    job, and a purge that fails must not be able to take the hub down with it.
    """
    import asyncio

    from backend.services.retention_service import from_config

    logger = get_logger(context="retention")
    while True:
        session = get_session()
        try:
            service = from_config(session, config)
            if not service.enabled:
                logger.debug("retention disabled; loop idle")
            else:
                await asyncio.to_thread(service.purge)
        except asyncio.CancelledError:
            raise
        except Exception as e:
            logger.exception(f"Retention pass failed (the hub is unaffected): {e}")
        finally:
            session.close()
        await asyncio.sleep(24 * 60 * 60)


# --- Service API Sub-Application ---
service_app = FastAPI(
    title="Nova Hub - Service API",
    description="""
# Service API for nova_client

This API is used by BBS clients running nova_client to:

- **Authenticate** using OAuth2 client credentials flow
- **Upload packets** generated by BRE/FE door games
- **Download packets** destined for their BBS (poll `/leagues/{league_id}/packets?unread=true`)
- **Download nodelists** for league member information

## Authentication

All endpoints except `/auth/token` require OAuth2 Bearer token authentication.

1. Request a token: `POST /service/api/v1/auth/token`, form-encoded, with
   `grant_type=client_credentials`, `client_id` and `client_secret`.
   This is the **client credentials** grant - credentials go in the request
   body, not in a Basic auth header. No scopes are used.
2. Use the token: `Authorization: Bearer <token>` header.

Tokens are JWTs and expire after `jwt_expiry_hours` (24 by default).

Note for anyone reading the generated OpenAPI schema: the security scheme is
declared as `OAuth2PasswordBearer` because that is FastAPI's helper for
extracting a bearer token from the `Authorization` header. It describes how the
token is *presented*, not how it is *obtained* - the token endpoint accepts
`client_credentials` and nothing else.

## No WebSocket

There is no WebSocket endpoint. Clients discover work by polling
`GET /service/api/v1/leagues/{league_id}/packets?unread=true`. Downloading a
packet is itself the acknowledgement: the hub marks it read when it serves it,
so it drops out of subsequent `unread=true` responses.

## Packet Naming Convention

Packets follow the format: `<league><game><source><dest>.<seq>`

- **league**: 3-digit league number (e.g., 555)
- **game**: B (BRE) or F (FE)
- **source**: 2-digit hex BBS index (01-FF)
- **dest**: 2-digit hex BBS index (01-FF)
- **seq**: 3-digit sequence number (000-999, wraps)

Example: `555B0201.001` = BRE League 555, from BBS 02 to BBS 01, sequence 1
    """,
    version=__version__,
    docs_url="/docs",
    redoc_url="/redoc",
    license_info={"name": "MIT"},
)

service_app.add_middleware(AuthContextMiddleware)
service_app.include_router(service_router, prefix="/api/v1")


